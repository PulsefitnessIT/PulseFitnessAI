/**
 * Public Customer Tracking page — Iter 216h83.
 *
 * Uber-style live view at /track/<token>. No auth. Token is the gate.
 * Polls every 30 s while the case is in-flight, every 5 min once closed.
 *
 * Designed to be shared via SMS / email / WhatsApp — must look great on
 * mobile, must be brand-friendly, and must never leak operational data
 * (commercial counts, internal notes, engineer email/phone).
 */
import React, { useCallback, useEffect, useState } from 'react';
import { useParams } from 'react-router-dom';
import axios from 'axios';
import {
  MapPin, Clock, CheckCircle, CheckCircle2, Wrench, Loader2, Truck, Star, AlertCircle, Send,
} from 'lucide-react';

const API = process.env.REACT_APP_BACKEND_URL ? `${process.env.REACT_APP_BACKEND_URL}/api` : '/api';

const STAGE_TO_INDEX = {
  new: 0,
  triaged: 0,
  assigned: 0,
  en_route: 1,
  on_site: 2,
  paused_parts: 2,
  paused_customer: 2,
  repaired: 3,
  awaiting_sign_off: 3,
  closed: 3,
  invoiced: 3,
};

function fmtTime(iso) {
  if (!iso) return '';
  try {
    return new Date(iso).toLocaleString(undefined, { dateStyle: 'short', timeStyle: 'short' });
  } catch {
    return iso;
  }
}

function fmtRelative(iso) {
  if (!iso) return '';
  const diff = Date.now() - new Date(iso).getTime();
  const m = Math.round(diff / 60000);
  if (m < 1) return 'just now';
  if (m < 60) return `${m} min ago`;
  const h = Math.round(m / 60);
  if (h < 24) return `${h}h ago`;
  const d = Math.round(h / 24);
  return `${d}d ago`;
}

export default function PublicTrackingPage() {
  const { token } = useParams();
  const [data, setData] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);
  // Iter 216h90 — NPS feedback form state
  const [fbStars, setFbStars] = useState(0);
  const [fbNps, setFbNps] = useState(null);
  const [fbComment, setFbComment] = useState('');
  const [fbBusy, setFbBusy] = useState(false);
  const [fbThanks, setFbThanks] = useState(false);
  // Iter 220l — "Request this engineer again" CTA state.
  const [preferRequested, setPreferRequested] = useState(false);
  const [preferBusy, setPreferBusy] = useState(false);
  const requestPreferredEngineer = useCallback(async () => {
    setPreferBusy(true);
    try {
      await axios.post(
        `${API}/svc/public/track/${encodeURIComponent(token)}/preferred-engineer`,
        {},
      );
      setPreferRequested(true);
    } catch (_err) {
      // Stay silent on 409 (no engineer) — button is only shown when one is present
    } finally {
      setPreferBusy(false);
    }
  }, [token]);

  const fetchTracking = useCallback(async () => {
    try {
      const r = await axios.get(`${API}/svc/public/track/${encodeURIComponent(token)}`);
      setData(r.data);
      setError(null);
    } catch (e) {
      if (e?.response?.status === 404) {
        setError('not_found');
      } else {
        setError('generic');
      }
    } finally {
      setLoading(false);
    }
  }, [token]);

  useEffect(() => {
    fetchTracking();
  }, [fetchTracking]);

  // Auto-poll: 30s while in-flight, 5 min once closed.
  useEffect(() => {
    const closed = data?.is_complete;
    const ms = closed ? 5 * 60 * 1000 : 30 * 1000;
    const id = setInterval(fetchTracking, ms);
    return () => clearInterval(id);
  }, [data?.is_complete, fetchTracking]);

  const submitFeedback = async () => {
    if (fbBusy) return;
    setFbBusy(true);
    try {
      const payload = {};
      if (fbStars) payload.rating = fbStars;
      if (fbNps !== null) payload.nps_score = fbNps;
      if (fbComment.trim()) payload.comment = fbComment.trim();
      if (Object.keys(payload).length === 0) {
        setFbBusy(false);
        return;
      }
      await axios.post(`${API}/svc/public/track/${encodeURIComponent(token)}/feedback`, payload);
      setFbThanks(true);
      // Refresh once after a small delay so the "Sent" badge appears
      setTimeout(fetchTracking, 800);
    } catch {
      // Show inline only — no toast lib on a public page.
      setFbThanks(false);
    } finally {
      setFbBusy(false);
    }
  };

  if (loading) {
    return (
      <div className="min-h-screen flex items-center justify-center bg-slate-50" data-testid="track-loading">
        <Loader2 className="animate-spin opacity-60" size={28} />
      </div>
    );
  }
  if (error === 'not_found') {
    return (
      <div className="min-h-screen flex items-center justify-center bg-slate-50 p-6" data-testid="track-not-found">
        <div className="text-center max-w-md">
          <AlertCircle className="mx-auto text-slate-400 mb-3" size={48} />
          <h1 className="text-xl font-bold text-slate-800 mb-2">Tracking link not found</h1>
          <p className="text-sm text-slate-500">
            This link may have expired, been regenerated by your service team, or never existed.
            Please contact your service desk for a fresh link.
          </p>
        </div>
      </div>
    );
  }
  if (error) {
    return (
      <div className="min-h-screen flex items-center justify-center bg-slate-50 p-6">
        <p className="text-slate-500" data-testid="track-error">Unable to load tracking right now. We'll keep trying…</p>
      </div>
    );
  }

  const stageIdx = STAGE_TO_INDEX[data.status] ?? 0;
  const brand = data.organization?.brand_primary || '#0055FF';
  const customerName = data.customer_first_name || 'there';

  return (
    <div className="min-h-screen bg-slate-50" data-testid="track-page">
      {/* Header */}
      <header className="text-white pt-8 pb-6 px-5" style={{ background: brand }} data-testid="track-header">
        <div className="max-w-2xl mx-auto">
          {data.organization?.logo_url ? (
            <img src={data.organization.logo_url} alt={data.organization.name} className="h-8 mb-4 opacity-95" loading="eager" decoding="async" />
          ) : (
            <p className="text-xs uppercase tracking-wider opacity-80 mb-1 font-bold">{data.organization?.name}</p>
          )}
          <h1 className="text-2xl font-extrabold leading-tight" data-testid="track-title">
            Hi {customerName}, here's your service visit.
          </h1>
          <p className="text-sm opacity-85 mt-1" data-testid="track-reference">
            Ref {data.reference} · {data.title}
          </p>
        </div>
      </header>

      <main className="max-w-2xl mx-auto px-5 pb-12 -mt-4 space-y-4">
        {/* Live status card */}
        <section className="rounded-2xl bg-white shadow-sm border border-slate-200 p-5" data-testid="track-status-card">
          <div className="flex items-center gap-2">
            <span
              className="inline-flex items-center gap-1.5 px-3 py-1 rounded-full text-xs font-extrabold uppercase tracking-wider"
              style={{
                background: data.is_complete
                  ? '#dcfce7'
                  : data.status_tone === 'warn'
                  ? '#fef9c3'
                  : data.status_tone === 'active'
                  ? `${brand}22`
                  : '#e2e8f0',
                color: data.is_complete ? '#166534' : data.status_tone === 'warn' ? '#92400e' : brand,
              }}
              data-testid="track-status-pill"
            >
              {data.is_complete ? <CheckCircle size={12} /> : <Truck size={12} />}
              {data.status_label}
            </span>
            {data.updated_at ? (
              <span className="text-xs text-slate-400 ml-auto">Updated {fmtRelative(data.updated_at)}</span>
            ) : null}
          </div>
          <p className="text-base text-slate-800 mt-3" data-testid="track-status-blurb">{data.status_blurb}</p>

          {/* Iter 216h91 — Live ETA when we have a position */}
          {data.eta?.label ? (
            <div className="mt-3 flex items-center gap-2 px-3 py-2 rounded-xl border border-blue-200 bg-blue-50" data-testid="track-eta">
              <Truck size={14} className="text-blue-600" />
              <p className="text-sm font-bold text-blue-900">{data.eta.label}</p>
              {data.eta.distance_km ? (
                <span className="text-xs text-blue-700">· {data.eta.distance_km} km</span>
              ) : null}
            </div>
          ) : null}

          {/* Progress bar */}
          <div className="mt-5">
            <div className="flex items-center gap-1" data-testid="track-progress">
              {data.stages.map((stage, i) => {
                const reached = i <= stageIdx;
                return (
                  <React.Fragment key={stage.key}>
                    <div
                      className="w-6 h-6 rounded-full flex items-center justify-center text-[10px] font-extrabold"
                      style={{
                        background: reached ? brand : '#e2e8f0',
                        color: reached ? '#fff' : '#94a3b8',
                      }}
                      data-testid={`track-stage-${stage.key}`}
                    >
                      {i < stageIdx ? '✓' : i + 1}
                    </div>
                    {i < data.stages.length - 1 ? (
                      <div
                        className="flex-1 h-1 rounded-full"
                        style={{ background: i < stageIdx ? brand : '#e2e8f0' }}
                      />
                    ) : null}
                  </React.Fragment>
                );
              })}
            </div>
            <div className="flex justify-between mt-1.5">
              {data.stages.map((stage) => (
                <span key={stage.key} className="text-[10px] font-bold uppercase tracking-wider text-slate-500">{stage.label}</span>
              ))}
            </div>
          </div>
        </section>

        {/* Engineer card */}
        {data.engineer ? (
          <section className="rounded-2xl bg-white shadow-sm border border-slate-200 p-5" data-testid="track-engineer-card">
            <div className="flex items-center justify-between mb-3">
              <p className="text-[10px] font-bold uppercase tracking-wider text-slate-500">Your engineer</p>
              {data.engineer.verified ? (
                <span
                  className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full text-[10px] font-extrabold uppercase tracking-wider"
                  style={{ background: '#dcfce7', color: '#166534' }}
                  data-testid="track-engineer-verified"
                >
                  ✓ Verified
                </span>
              ) : null}
            </div>
            <div className="flex items-center gap-3">
              {data.engineer.photo_url ? (
                <img
                  src={data.engineer.photo_url}
                  alt={data.engineer.first_name}
                  className="w-14 h-14 rounded-full object-cover border-2"
                  style={{ borderColor: brand }}
                  data-testid="track-engineer-photo"
                  loading="lazy"
                  decoding="async"
                />
              ) : (
                <div
                  className="w-14 h-14 rounded-full flex items-center justify-center text-xl font-extrabold text-white"
                  style={{ background: brand }}
                >
                  {(data.engineer.first_name || 'E')[0].toUpperCase()}
                </div>
              )}
              <div className="flex-1 min-w-0">
                <p className="font-bold text-slate-800 text-base" data-testid="track-engineer-name">
                  {data.engineer.first_name}
                </p>
                <div className="flex flex-wrap gap-3 text-xs text-slate-500 mt-0.5">
                  {(data.engineer.avg_rating != null && data.engineer.ratings_count > 0) ? (
                    <span className="inline-flex items-center gap-0.5" data-testid="track-engineer-rating">
                      <Star size={11} className="text-amber-400" fill="currentColor" />
                      <span className="font-bold text-slate-700">{data.engineer.avg_rating}</span>
                      <span>· {data.engineer.ratings_count} review{data.engineer.ratings_count === 1 ? '' : 's'}</span>
                    </span>
                  ) : null}
                  {(data.engineer.jobs_completed_90d || 0) > 0 ? (
                    <span data-testid="track-engineer-jobs">
                      {data.engineer.jobs_completed_90d} job{data.engineer.jobs_completed_90d === 1 ? '' : 's'} in 90 days
                    </span>
                  ) : null}
                  {data.engineer.years_experience ? (
                    <span data-testid="track-engineer-experience">
                      {data.engineer.years_experience}+ yrs experience
                    </span>
                  ) : null}
                </div>
              </div>
            </div>
            {data.engineer.skills?.length ? (
              <div className="flex flex-wrap gap-1.5 mt-3">
                {data.engineer.skills.map((s) => (
                  <span
                    key={s}
                    className="px-2 py-0.5 rounded-full text-[10px] font-bold uppercase tracking-wider"
                    style={{ background: `${brand}1A`, color: brand }}
                    data-testid={`track-engineer-skill-${s.replace(/\W+/g, '_')}`}
                  >
                    {s}
                  </span>
                ))}
              </div>
            ) : null}
            {data.engineer.qualifications?.length ? (
              <div className="flex flex-wrap gap-1.5 mt-2">
                {data.engineer.qualifications.map((q) => (
                  <span
                    key={q}
                    className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full text-[10px] font-bold tracking-wider border border-emerald-200 bg-emerald-50 text-emerald-700"
                    data-testid={`track-engineer-qual-${q.replace(/\W+/g, '_')}`}
                  >
                    ✓ {q}
                  </span>
                ))}
              </div>
            ) : null}
          </section>
        ) : null}

        {/* Iter 216h91 — Live tracking map (en_route / on_site only) */}
        {data.engineer_location && data.site_location ? (
          <section className="rounded-2xl bg-white shadow-sm border border-slate-200 overflow-hidden" data-testid="track-live-map">
            <div className="px-5 pt-5 flex items-center justify-between">
              <p className="text-[10px] font-bold uppercase tracking-wider text-slate-500">Live location</p>
              <span className="text-[10px] font-bold uppercase tracking-wider text-emerald-600 flex items-center gap-1">
                <span className="w-1.5 h-1.5 rounded-full bg-emerald-500 animate-pulse" />
                Live · updates ~1 min
              </span>
            </div>
            <iframe
              title="Engineer live location"
              src={`https://www.openstreetmap.org/export/embed.html?bbox=${
                Math.min(data.engineer_location.lng, data.site_location.lng) - 0.02},${
                Math.min(data.engineer_location.lat, data.site_location.lat) - 0.02},${
                Math.max(data.engineer_location.lng, data.site_location.lng) + 0.02},${
                Math.max(data.engineer_location.lat, data.site_location.lat) + 0.02}&layer=mapnik&marker=${
                data.engineer_location.lat},${data.engineer_location.lng}`}
              className="w-full mt-3"
              style={{ height: 220, border: 0 }}
              loading="lazy"
            />
            <p className="px-5 py-2.5 text-[10px] text-slate-400 leading-relaxed border-t border-slate-100">
              Map shows your engineer's approximate position. Location refresh stops automatically once they arrive on site.
            </p>
          </section>
        ) : null}

        {/* Site card */}
        {data.site?.name || data.site?.postcode ? (
          <section className="rounded-2xl bg-white shadow-sm border border-slate-200 p-5" data-testid="track-site-card">
            <p className="text-[10px] font-bold uppercase tracking-wider text-slate-500 mb-2">Visit location</p>
            <p className="font-bold text-slate-800 flex items-center gap-1.5">
              <MapPin size={14} className="opacity-60" />
              {data.site.name || 'Site'}
            </p>
            {(data.site.address || data.site.postcode) ? (
              <p className="text-sm text-slate-600 mt-1 ml-5">
                {[data.site.address, data.site.postcode].filter(Boolean).join(', ')}
              </p>
            ) : null}
            {data.asset_name ? (
              <p className="text-sm text-slate-500 mt-1 ml-5 flex items-center gap-1.5">
                <Wrench size={12} /> {data.asset_name}
              </p>
            ) : null}
          </section>
        ) : null}

        {/* Timeline */}
        {data.events?.length ? (
          <section className="rounded-2xl bg-white shadow-sm border border-slate-200 p-5" data-testid="track-timeline">
            <p className="text-[10px] font-bold uppercase tracking-wider text-slate-500 mb-3">Recent activity</p>
            <ol className="space-y-2.5">
              {data.events.slice(0, 5).map((ev, i) => (
                <li key={i} className="flex items-start gap-2.5 text-sm">
                  <span className="mt-1.5 w-1.5 h-1.5 rounded-full flex-shrink-0" style={{ background: brand }} />
                  <div className="min-w-0 flex-1">
                    <p className="text-slate-800">{ev.body || ev.type.replace('_', ' ')}</p>
                    <p className="text-xs text-slate-400 mt-0.5 flex items-center gap-1">
                      <Clock size={10} /> {fmtTime(ev.at)}
                    </p>
                  </div>
                </li>
              ))}
            </ol>
          </section>
        ) : null}

        {/* Iter 216h90 — Complete + NPS feedback */}
        {data.is_complete ? (
          <section className="rounded-2xl bg-emerald-50 border border-emerald-200 p-5" data-testid="track-complete-card">
            <p className="text-emerald-900 font-extrabold flex items-center gap-2">
              <CheckCircle size={18} /> All done — thanks {customerName}.
            </p>
            {data.report_sent ? (
              <p className="text-xs text-emerald-700 mt-1">A copy of your service report has been emailed to you.</p>
            ) : null}
            {data.feedback_captured || fbThanks ? (
              <div className="mt-3 pt-3 border-t border-emerald-200 space-y-3" data-testid="track-feedback-thanks">
                <div className="flex items-center gap-2 text-sm text-emerald-800">
                  <Star size={14} fill="currentColor" className="text-amber-500" />
                  <span>Thank you — your feedback has been recorded.</span>
                </div>
                {/* Iter 220l — Request this engineer again. Only when an
                    engineer is attached AND the customer has just left
                    feedback (so they've reflected on the experience). */}
                {data.engineer && data.engineer.first_name ? (
                  preferRequested ? (
                    <p
                      className="inline-flex items-center gap-2 text-xs text-emerald-900 bg-emerald-100 border border-emerald-300 px-3 py-2 rounded-lg"
                      data-testid="track-engineer-requested-confirm"
                    >
                      <CheckCircle2 size={12} />
                      <span>
                        We've let <b>{data.engineer.first_name}</b> know you'd like them
                        for your next job.
                      </span>
                    </p>
                  ) : (
                    <button
                      type="button"
                      onClick={requestPreferredEngineer}
                      disabled={preferBusy}
                      className="w-full inline-flex items-center justify-center gap-1.5 px-3 py-2 rounded-lg bg-white border border-emerald-300 hover:bg-emerald-50 text-emerald-800 text-xs font-bold disabled:opacity-50 transition-colors"
                      data-testid="track-engineer-request-again"
                    >
                      {preferBusy ? 'Sending…' : `Request ${data.engineer.first_name} for next time →`}
                    </button>
                  )
                ) : null}
              </div>
            ) : (
              <div className="mt-3 pt-3 border-t border-emerald-200 space-y-3" data-testid="track-feedback-form">
                <div>
                  <p className="text-xs font-bold uppercase tracking-wider text-emerald-800 mb-1.5">
                    How was the visit?
                  </p>
                  <div className="flex items-center gap-1" data-testid="track-feedback-stars">
                    {[1, 2, 3, 4, 5].map((n) => (
                      <button
                        type="button"
                        key={n}
                        onClick={() => setFbStars(n)}
                        className="p-1"
                        aria-label={`${n} star${n === 1 ? '' : 's'}`}
                        data-testid={`track-feedback-star-${n}`}
                      >
                        <Star
                          size={26}
                          className={fbStars >= n ? 'text-amber-400' : 'text-slate-300'}
                          fill={fbStars >= n ? 'currentColor' : 'none'}
                        />
                      </button>
                    ))}
                  </div>
                </div>
                <div>
                  <p className="text-xs font-bold uppercase tracking-wider text-emerald-800 mb-1.5">
                    How likely are you to recommend us? <span className="text-slate-500 font-normal">(0–10)</span>
                  </p>
                  <div className="flex flex-wrap gap-1" data-testid="track-feedback-nps">
                    {Array.from({ length: 11 }).map((_, n) => (
                      <button
                        type="button"
                        key={n}
                        onClick={() => setFbNps(n)}
                        className={
                          'w-8 h-8 rounded-md text-xs font-bold transition-colors ' +
                          (fbNps === n
                            ? 'bg-emerald-600 text-white'
                            : 'bg-white border border-emerald-200 text-emerald-800 hover:bg-emerald-100')
                        }
                        data-testid={`track-feedback-nps-${n}`}
                      >
                        {n}
                      </button>
                    ))}
                  </div>
                </div>
                <div>
                  <textarea
                    value={fbComment}
                    onChange={(e) => setFbComment(e.target.value)}
                    placeholder="What stood out? Any suggestions? (optional)"
                    rows={3}
                    maxLength={1500}
                    className="w-full px-3 py-2 rounded-lg text-sm bg-white border border-emerald-200 focus:outline-none focus:ring-2 focus:ring-emerald-300"
                    data-testid="track-feedback-comment"
                  />
                </div>
                <button
                  type="button"
                  onClick={submitFeedback}
                  disabled={fbBusy || (fbStars === 0 && fbNps === null && !fbComment.trim())}
                  className="w-full inline-flex items-center justify-center gap-1.5 px-4 py-2.5 rounded-lg text-sm font-bold text-white disabled:opacity-50"
                  style={{ background: '#059669' }}
                  data-testid="track-feedback-submit"
                >
                  <Send size={13} /> {fbBusy ? 'Sending…' : 'Send feedback'}
                </button>
              </div>
            )}
          </section>
        ) : null}

        {/* Footer */}
        <footer className="text-center text-xs text-slate-400 pt-4" data-testid="track-footer">
          Powered by {data.organization?.name} · This page auto-refreshes
        </footer>
      </main>
    </div>
  );
}
