/**
 * Public Customer Tracking page — Iter 216h83.
 *
 * Uber-style live view at /track/<token>. No auth. Token is the gate.
 * Polls every 30 s while the case is in-flight, every 5 min once closed.
 *
 * Designed to be shared via SMS / email / WhatsApp — must look great on
 * mobile, must be brand-friendly, and must never leak operational data
 * (commercial counts, internal notes, engineer email/phone).
 */
import React, { useCallback, useEffect, useState } from 'react';
import { useParams } from 'react-router-dom';
import axios from 'axios';
import {
  MapPin, Clock, CheckCircle, Wrench, Loader2, Phone, Truck, Star, AlertCircle,
} from 'lucide-react';

const API = process.env.REACT_APP_BACKEND_URL ? `${process.env.REACT_APP_BACKEND_URL}/api` : '/api';

const STAGE_TO_INDEX = {
  new: 0,
  triaged: 0,
  assigned: 0,
  en_route: 1,
  on_site: 2,
  paused_parts: 2,
  paused_customer: 2,
  repaired: 3,
  awaiting_sign_off: 3,
  closed: 3,
  invoiced: 3,
};

function fmtTime(iso) {
  if (!iso) return '';
  try {
    return new Date(iso).toLocaleString(undefined, { dateStyle: 'short', timeStyle: 'short' });
  } catch {
    return iso;
  }
}

function fmtRelative(iso) {
  if (!iso) return '';
  const diff = Date.now() - new Date(iso).getTime();
  const m = Math.round(diff / 60000);
  if (m < 1) return 'just now';
  if (m < 60) return `${m} min ago`;
  const h = Math.round(m / 60);
  if (h < 24) return `${h}h ago`;
  const d = Math.round(h / 24);
  return `${d}d ago`;
}

export default function PublicTrackingPage() {
  const { token } = useParams();
  const [data, setData] = useState(null);
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState(null);

  const fetchTracking = useCallback(async () => {
    try {
      const r = await axios.get(`${API}/svc/public/track/${encodeURIComponent(token)}`);
      setData(r.data);
      setError(null);
    } catch (e) {
      if (e?.response?.status === 404) {
        setError('not_found');
      } else {
        setError('generic');
      }
    } finally {
      setLoading(false);
    }
  }, [token]);

  useEffect(() => {
    fetchTracking();
  }, [fetchTracking]);

  // Auto-poll: 30s while in-flight, 5 min once closed.
  useEffect(() => {
    const closed = data?.is_complete;
    const ms = closed ? 5 * 60 * 1000 : 30 * 1000;
    const id = setInterval(fetchTracking, ms);
    return () => clearInterval(id);
  }, [data?.is_complete, fetchTracking]);

  if (loading) {
    return (
      <div className="min-h-screen flex items-center justify-center bg-slate-50" data-testid="track-loading">
        <Loader2 className="animate-spin opacity-60" size={28} />
      </div>
    );
  }
  if (error === 'not_found') {
    return (
      <div className="min-h-screen flex items-center justify-center bg-slate-50 p-6" data-testid="track-not-found">
        <div className="text-center max-w-md">
          <AlertCircle className="mx-auto text-slate-400 mb-3" size={48} />
          <h1 className="text-xl font-bold text-slate-800 mb-2">Tracking link not found</h1>
          <p className="text-sm text-slate-500">
            This link may have expired, been regenerated by your service team, or never existed.
            Please contact your service desk for a fresh link.
          </p>
        </div>
      </div>
    );
  }
  if (error) {
    return (
      <div className="min-h-screen flex items-center justify-center bg-slate-50 p-6">
        <p className="text-slate-500" data-testid="track-error">Unable to load tracking right now. We'll keep trying…</p>
      </div>
    );
  }

  const stageIdx = STAGE_TO_INDEX[data.status] ?? 0;
  const brand = data.organization?.brand_primary || '#0055FF';
  const customerName = data.customer_first_name || 'there';

  return (
    <div className="min-h-screen bg-slate-50" data-testid="track-page">
      {/* Header */}
      <header className="text-white pt-8 pb-6 px-5" style={{ background: brand }} data-testid="track-header">
        <div className="max-w-2xl mx-auto">
          {data.organization?.logo_url ? (
            <img src={data.organization.logo_url} alt={data.organization.name} className="h-8 mb-4 opacity-95" />
          ) : (
            <p className="text-xs uppercase tracking-wider opacity-80 mb-1 font-bold">{data.organization?.name}</p>
          )}
          <h1 className="text-2xl font-extrabold leading-tight" data-testid="track-title">
            Hi {customerName}, here's your service visit.
          </h1>
          <p className="text-sm opacity-85 mt-1" data-testid="track-reference">
            Ref {data.reference} · {data.title}
          </p>
        </div>
      </header>

      <main className="max-w-2xl mx-auto px-5 pb-12 -mt-4 space-y-4">
        {/* Live status card */}
        <section className="rounded-2xl bg-white shadow-sm border border-slate-200 p-5" data-testid="track-status-card">
          <div className="flex items-center gap-2">
            <span
              className="inline-flex items-center gap-1.5 px-3 py-1 rounded-full text-xs font-extrabold uppercase tracking-wider"
              style={{
                background: data.is_complete
                  ? '#dcfce7'
                  : data.status_tone === 'warn'
                  ? '#fef9c3'
                  : data.status_tone === 'active'
                  ? `${brand}22`
                  : '#e2e8f0',
                color: data.is_complete ? '#166534' : data.status_tone === 'warn' ? '#92400e' : brand,
              }}
              data-testid="track-status-pill"
            >
              {data.is_complete ? <CheckCircle size={12} /> : <Truck size={12} />}
              {data.status_label}
            </span>
            {data.updated_at ? (
              <span className="text-xs text-slate-400 ml-auto">Updated {fmtRelative(data.updated_at)}</span>
            ) : null}
          </div>
          <p className="text-base text-slate-800 mt-3" data-testid="track-status-blurb">{data.status_blurb}</p>

          {/* Progress bar */}
          <div className="mt-5">
            <div className="flex items-center gap-1" data-testid="track-progress">
              {data.stages.map((stage, i) => {
                const reached = i <= stageIdx;
                return (
                  <React.Fragment key={stage.key}>
                    <div
                      className="w-6 h-6 rounded-full flex items-center justify-center text-[10px] font-extrabold"
                      style={{
                        background: reached ? brand : '#e2e8f0',
                        color: reached ? '#fff' : '#94a3b8',
                      }}
                      data-testid={`track-stage-${stage.key}`}
                    >
                      {i < stageIdx ? '✓' : i + 1}
                    </div>
                    {i < data.stages.length - 1 ? (
                      <div
                        className="flex-1 h-1 rounded-full"
                        style={{ background: i < stageIdx ? brand : '#e2e8f0' }}
                      />
                    ) : null}
                  </React.Fragment>
                );
              })}
            </div>
            <div className="flex justify-between mt-1.5">
              {data.stages.map((stage) => (
                <span key={stage.key} className="text-[10px] font-bold uppercase tracking-wider text-slate-500">{stage.label}</span>
              ))}
            </div>
          </div>
        </section>

        {/* Engineer card */}
        {data.engineer ? (
          <section className="rounded-2xl bg-white shadow-sm border border-slate-200 p-5" data-testid="track-engineer-card">
            <p className="text-[10px] font-bold uppercase tracking-wider text-slate-500 mb-2">Your engineer</p>
            <div className="flex items-center gap-3">
              <div
                className="w-12 h-12 rounded-full flex items-center justify-center text-lg font-extrabold text-white"
                style={{ background: brand }}
              >
                {(data.engineer.first_name || 'E')[0].toUpperCase()}
              </div>
              <div className="flex-1 min-w-0">
                <p className="font-bold text-slate-800" data-testid="track-engineer-name">{data.engineer.first_name}</p>
                {data.engineer.skills?.length ? (
                  <div className="flex flex-wrap gap-1 mt-1">
                    {data.engineer.skills.slice(0, 4).map((s) => (
                      <span
                        key={s}
                        className="px-2 py-0.5 rounded-full text-[10px] font-bold uppercase tracking-wider"
                        style={{ background: `${brand}1A`, color: brand }}
                      >
                        {s}
                      </span>
                    ))}
                  </div>
                ) : null}
              </div>
            </div>
          </section>
        ) : null}

        {/* Site card */}
        {data.site?.name || data.site?.postcode ? (
          <section className="rounded-2xl bg-white shadow-sm border border-slate-200 p-5" data-testid="track-site-card">
            <p className="text-[10px] font-bold uppercase tracking-wider text-slate-500 mb-2">Visit location</p>
            <p className="font-bold text-slate-800 flex items-center gap-1.5">
              <MapPin size={14} className="opacity-60" />
              {data.site.name || 'Site'}
            </p>
            {(data.site.address || data.site.postcode) ? (
              <p className="text-sm text-slate-600 mt-1 ml-5">
                {[data.site.address, data.site.postcode].filter(Boolean).join(', ')}
              </p>
            ) : null}
            {data.asset_name ? (
              <p className="text-sm text-slate-500 mt-1 ml-5 flex items-center gap-1.5">
                <Wrench size={12} /> {data.asset_name}
              </p>
            ) : null}
          </section>
        ) : null}

        {/* Timeline */}
        {data.events?.length ? (
          <section className="rounded-2xl bg-white shadow-sm border border-slate-200 p-5" data-testid="track-timeline">
            <p className="text-[10px] font-bold uppercase tracking-wider text-slate-500 mb-3">Recent activity</p>
            <ol className="space-y-2.5">
              {data.events.slice(0, 5).map((ev, i) => (
                <li key={i} className="flex items-start gap-2.5 text-sm">
                  <span className="mt-1.5 w-1.5 h-1.5 rounded-full flex-shrink-0" style={{ background: brand }} />
                  <div className="min-w-0 flex-1">
                    <p className="text-slate-800">{ev.body || ev.type.replace('_', ' ')}</p>
                    <p className="text-xs text-slate-400 mt-0.5 flex items-center gap-1">
                      <Clock size={10} /> {fmtTime(ev.at)}
                    </p>
                  </div>
                </li>
              ))}
            </ol>
          </section>
        ) : null}

        {/* Complete + rating reminder */}
        {data.is_complete ? (
          <section className="rounded-2xl bg-emerald-50 border border-emerald-200 p-5" data-testid="track-complete-card">
            <p className="text-emerald-900 font-extrabold flex items-center gap-2">
              <CheckCircle size={18} /> All done — thanks {customerName}.
            </p>
            {data.rating_captured ? (
              <p className="text-sm text-emerald-800 mt-2 flex items-center gap-1.5">
                <Star size={14} fill="currentColor" /> You've rated this visit. Thank you!
              </p>
            ) : (
              <p className="text-sm text-emerald-800 mt-2">
                Your service team will be in touch shortly. If you'd like to leave feedback, reply to your service desk email.
              </p>
            )}
            {data.report_sent ? (
              <p className="text-xs text-emerald-700 mt-1">A copy of your service report has been emailed to you.</p>
            ) : null}
          </section>
        ) : null}

        {/* Footer */}
        <footer className="text-center text-xs text-slate-400 pt-4" data-testid="track-footer">
          Powered by {data.organization?.name} · This page auto-refreshes
        </footer>
      </main>
    </div>
  );
}
