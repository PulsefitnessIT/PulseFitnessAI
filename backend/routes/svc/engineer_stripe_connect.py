"""Iter 216h132 — Stripe Connect (Express) for Engineer Partners.

Engineer-facing endpoints to onboard a Stripe Express account so that
invoices generated by the engineer settle into THEIR Stripe balance
(Direct Charges with `stripe_account=acct_xxx`). The platform takes
no application fee — the £30/mo subscription already covers revenue.

Endpoints (all `/api/svc/engineer/stripe/connect`):
  • GET    /status                       → connection state (cached + live)
  • POST   /onboarding                   → create-or-fetch Express account + AccountLink
  • POST   /login-link                   → Express dashboard login link
  • POST   /refresh                      → re-sync account flags from Stripe

Webhooks (public, no auth):
  • POST   /webhooks/stripe/connect      → handles `account.updated`,
                                            `account.application.deauthorized`

The connected account id is persisted at
  `partner_engineers.payout.stripe_account_id`
and the cached capability flags at
  `partner_engineers.payout.stripe_connect = {
      charges_enabled, payouts_enabled, details_submitted,
      requirements_currently_due, last_synced_at
  }`
"""
from __future__ import annotations

import logging
import os
from datetime import datetime, timezone
from typing import Any

import stripe
from fastapi import APIRouter, Depends, HTTPException, Request

from routes.partners import require_engineer_app_access
from utils.auth import get_current_user
from utils.database import db

logger = logging.getLogger(__name__)

stripe.api_key = os.environ.get("STRIPE_API_KEY")
CONNECT_WEBHOOK_SECRET = (
    os.environ.get("STRIPE_CONNECT_WEBHOOK_SECRET")
    or os.environ.get("STRIPE_WEBHOOK_SECRET")
)

router = APIRouter(
    prefix="/svc/engineer/stripe/connect",
    tags=["Service Ops · Engineer Stripe Connect"],
    dependencies=[Depends(require_engineer_app_access)],
)
public_router = APIRouter(tags=["Public · Engineer Stripe Connect"])


# ───────────────────────── helpers ─────────────────────────

def _now() -> str:
    return datetime.now(timezone.utc).isoformat()


def _origin() -> str:
    return (
        os.environ.get("PUBLIC_ORIGIN")
        or os.environ.get("REACT_APP_BACKEND_URL")
        or ""
    ).rstrip("/")


async def _get_partner_for_user(user: dict) -> dict:
    partner = await db.partner_engineers.find_one(
        {"user_id": user["id"]}, {"_id": 0},
    )
    if not partner:
        raise HTTPException(404, "Partner profile not found — apply to the engineer network first")
    return partner


def _flags_from_account(account: Any) -> dict:
    """Distill the Stripe Account object into the cache shape."""
    req = getattr(account, "requirements", None) or {}
    currently_due = []
    if isinstance(req, dict):
        currently_due = req.get("currently_due") or []
    else:
        currently_due = getattr(req, "currently_due", None) or []
    return {
        "charges_enabled": bool(getattr(account, "charges_enabled", False)),
        "payouts_enabled": bool(getattr(account, "payouts_enabled", False)),
        "details_submitted": bool(getattr(account, "details_submitted", False)),
        "requirements_currently_due": list(currently_due),
        "last_synced_at": _now(),
    }


async def _persist_flags(partner_id: str, account_id: str, flags: dict) -> None:
    await db.partner_engineers.update_one(
        {"id": partner_id},
        {"$set": {
            "payout.stripe_account_id": account_id,
            "payout.stripe_connect": flags,
            "payout.method": "stripe_connect" if flags.get("charges_enabled") else "stripe_connect_pending",
            "updated_at": _now(),
        }},
    )


def _ensure_stripe_configured() -> None:
    if not stripe.api_key:
        raise HTTPException(500, "Stripe is not configured on this server")


def _shape_status(partner: dict) -> dict:
    payout = partner.get("payout") or {}
    cache = payout.get("stripe_connect") or {}
    account_id = payout.get("stripe_account_id")
    connected = bool(account_id)
    return {
        "connected": connected,
        "ready": connected and bool(cache.get("charges_enabled")),
        "account_id": account_id,
        "charges_enabled": connected and bool(cache.get("charges_enabled")),
        "payouts_enabled": connected and bool(cache.get("payouts_enabled")),
        "details_submitted": connected and bool(cache.get("details_submitted")),
        "requirements_currently_due": cache.get("requirements_currently_due") or [],
        "last_synced_at": cache.get("last_synced_at"),
    }


async def _sync_from_stripe(partner: dict) -> dict:
    """Refresh `partner_engineers.payout.stripe_connect` from Stripe."""
    _ensure_stripe_configured()
    account_id = (partner.get("payout") or {}).get("stripe_account_id")
    if not account_id:
        return partner
    try:
        acct = stripe.Account.retrieve(account_id)
    except stripe.error.StripeError as exc:  # type: ignore[attr-defined]
        logger.warning("[stripe_connect] retrieve(%s) failed: %s", account_id, exc)
        return partner
    flags = _flags_from_account(acct)
    await _persist_flags(partner["id"], account_id, flags)
    fresh = await db.partner_engineers.find_one({"id": partner["id"]}, {"_id": 0})
    return fresh or partner


# ───────────────────────── engineer endpoints ─────────────────────────


@router.get("/status")
async def get_connect_status(refresh: bool = False, user=Depends(get_current_user)):
    partner = await _get_partner_for_user(user)
    if refresh:
        partner = await _sync_from_stripe(partner)
    return _shape_status(partner)


@router.post("/refresh")
async def refresh_connect(user=Depends(get_current_user)):
    partner = await _get_partner_for_user(user)
    partner = await _sync_from_stripe(partner)
    return _shape_status(partner)


@router.post("/onboarding")
async def create_onboarding_link(user=Depends(get_current_user)):
    """Create a Stripe Express account if missing, then return a fresh
    hosted onboarding URL (`AccountLink`). Stripe AccountLinks are
    single-use and expire after ~5 minutes."""
    _ensure_stripe_configured()
    partner = await _get_partner_for_user(user)
    payout = partner.get("payout") or {}
    account_id = payout.get("stripe_account_id")

    if not account_id:
        try:
            acct = stripe.Account.create(
                type="express",
                country=(partner.get("country_code") or "GB").upper(),
                email=user.get("email"),
                capabilities={
                    "card_payments": {"requested": True},
                    "transfers":     {"requested": True},
                },
                business_type="individual",
                business_profile={
                    "name": partner.get("trading_name") or partner.get("full_name") or "GymAxis Engineer Partner",
                    "product_description": "Fitness equipment service & maintenance",
                    "mcc": "7623",  # A/C, refrigeration repair (closest available)
                    "url": (_origin() or "https://gymaxis.com"),
                    "support_email": user.get("email"),
                },
                metadata={
                    "platform": "gymaxis",
                    "partner_id": partner["id"],
                    "user_id":    user["id"],
                    "engineer_email": user.get("email") or "",
                },
            )
            account_id = acct.id
            flags = _flags_from_account(acct)
            await _persist_flags(partner["id"], account_id, flags)
        except stripe.error.StripeError as exc:  # type: ignore[attr-defined]
            logger.warning("[stripe_connect] Account.create failed: %s", exc)
            msg = exc.user_message or str(exc)
            # If the platform hasn't enabled Stripe Connect yet, surface
            # a clear, actionable error code so the UI can guide them.
            if "signed up for Connect" in (str(exc) or ""):
                raise HTTPException(503, {
                    "code": "stripe_connect_not_enabled",
                    "message": "GymAxis hasn't enabled Stripe Connect yet. "
                                "An admin needs to enable Connect at "
                                "https://dashboard.stripe.com/connect.",
                })
            raise HTTPException(502, f"Stripe error: {msg}")

    origin = _origin()
    refresh_url = f"{origin}/svc/engineer/payouts?onboarding=refresh" if origin else "https://gymaxis.com/"
    return_url  = f"{origin}/svc/engineer/payouts?onboarding=return"  if origin else "https://gymaxis.com/"
    try:
        link = stripe.AccountLink.create(
            account=account_id,
            refresh_url=refresh_url,
            return_url=return_url,
            type="account_onboarding",
            collect="eventually_due",
        )
    except stripe.error.StripeError as exc:  # type: ignore[attr-defined]
        logger.warning("[stripe_connect] AccountLink.create failed: %s", exc)
        raise HTTPException(502, f"Stripe error: {exc.user_message or str(exc)}")
    return {"ok": True, "url": link.url, "account_id": account_id, "expires_at": link.expires_at}


@router.post("/login-link")
async def create_login_link(user=Depends(get_current_user)):
    """One-time Express Dashboard login URL for the engineer."""
    _ensure_stripe_configured()
    partner = await _get_partner_for_user(user)
    account_id = (partner.get("payout") or {}).get("stripe_account_id")
    if not account_id:
        raise HTTPException(412, {"code": "engineer_not_connected",
                                   "message": "Connect Stripe first."})
    try:
        link = stripe.Account.create_login_link(account_id)
    except stripe.error.StripeError as exc:  # type: ignore[attr-defined]
        raise HTTPException(502, f"Stripe error: {exc.user_message or str(exc)}")
    return {"ok": True, "url": link.url}


