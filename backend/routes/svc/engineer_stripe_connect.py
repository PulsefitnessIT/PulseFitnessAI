@public_router.post("/webhooks/stripe/connect")
async def stripe_connect_webhook(request: Request):
    """Cache `account.updated` flags so the engineer dashboard reflects
    onboarding completion without forcing a manual refresh.

    Stripe-Signature uses `STRIPE_CONNECT_WEBHOOK_SECRET` (falls back to
    the main `STRIPE_WEBHOOK_SECRET` if not separately provisioned)."""
    payload = await request.body()
    sig = request.headers.get("stripe-signature")
    if CONNECT_WEBHOOK_SECRET and sig:
        try:
            event = stripe.Webhook.construct_event(payload, sig, CONNECT_WEBHOOK_SECRET)
        except stripe.error.SignatureVerificationError:  # type: ignore[attr-defined]
            raise HTTPException(400, "Invalid signature")
    else:
        # Allow unsigned bodies through only in non-prod (tests)
        try:
            event = stripe.Event.construct_from(
                __import__("json").loads(payload), stripe.api_key,
            )
        except Exception:
            raise HTTPException(400, "Invalid body")

    etype = event.get("type") if isinstance(event, dict) else event["type"]
    obj = event["data"]["object"]
    account_id = obj.get("id") if etype.startswith("account.") else None

    if etype == "account.updated" and account_id:
        partner = await db.partner_engineers.find_one(
            {"payout.stripe_account_id": account_id}, {"_id": 0},
        )
        if partner:
            flags = {
                "charges_enabled":  bool(obj.get("charges_enabled")),
                "payouts_enabled":  bool(obj.get("payouts_enabled")),
                "details_submitted": bool(obj.get("details_submitted")),
                "requirements_currently_due": (obj.get("requirements") or {}).get("currently_due") or [],
                "last_synced_at": _now(),
            }
            await _persist_flags(partner["id"], account_id, flags)
            return {"ok": True, "partner_id": partner["id"], "flags": flags}
        return {"ok": True, "ignored": True, "reason": "no matching partner"}

    if etype == "account.application.deauthorized" and account_id:
        await db.partner_engineers.update_one(
            {"payout.stripe_account_id": account_id},
            {"$set": {
                "payout.stripe_account_id": None,
                "payout.stripe_connect": None,
                "payout.method": "manual_csv",
                "updated_at": _now(),
            }},
        )
        return {"ok": True, "deauthorized": account_id}

    return {"ok": True, "ignored": True, "type": etype}


