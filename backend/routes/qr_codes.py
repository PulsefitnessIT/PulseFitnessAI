# Label-printer presets: key → (width_mm, height_mm, dpi)
QR_CARD_PRESETS = {
    "62x35": (62, 35, 300),   # Brother QL / DYMO LabelWriter default
    "62x62": (62, 62, 300),   # Square label
    "50x50": (50, 50, 300),   # Small square
    "a4":    (210, 297, 150),  # Full A4 for office printers (large)
    "card":  (90, 50, 300),   # Credit-card sized
}


def _mm_to_px(mm: float, dpi: int) -> int:
    return int(round(mm * dpi / 25.4))


def _wrap_text_to_width(draw, text: str, font, max_width_px: int) -> list:
    """Wrap text to fit within max_width_px; returns list of lines."""
    if not text:
        return []
    words = text.split()
    lines: list = []
    current = ""
    for w in words:
        candidate = f"{current} {w}".strip()
        bbox = draw.textbbox((0, 0), candidate, font=font)
        if (bbox[2] - bbox[0]) <= max_width_px or not current:
            current = candidate
        else:
            lines.append(current)
            current = w
    if current:
        lines.append(current)
    return lines


# QR card color palette (GymAxis brand)
_BRAND_BLUE = (0, 85, 255)
_INK = (20, 20, 20)
_MUTED = (120, 120, 120)
_SERIAL_COLOUR = (40, 40, 40)


def _build_qr_image(equipment_id: str, base_url: str):
    """Generate a branded QR image linking to the public scan URL."""
    scan_url = f"{base_url}/scan/{equipment_id}"
    qr = qrcode.QRCode(version=1, error_correction=qrcode.constants.ERROR_CORRECT_H, box_size=10, border=1)
    qr.add_data(scan_url)
    qr.make(fit=True)
    return qr.make_image(fill_color="black", back_color="white").convert("RGB")


def _load_qr_fonts(h_px: int, landscape: bool):
    """Load fonts in 5 sizes, falling back to default if DejaVu isn't available."""
    from PIL import ImageFont
    try:
        ratios = (0.15, 0.11, 0.09, 0.10, 0.075) if landscape else (0.09, 0.07, 0.06, 0.065, 0.05)
        bold = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
        regular = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
        mono = "/usr/share/fonts/truetype/dejavu/DejaVuSansMono-Bold.ttf"
        return {
            "header": ImageFont.truetype(bold,    int(h_px * ratios[0])),
            "model":  ImageFont.truetype(bold,    int(h_px * ratios[1])),
            "sub":    ImageFont.truetype(regular, int(h_px * ratios[2])),
            "mono":   ImageFont.truetype(mono,    int(h_px * ratios[3])),
            "scan":   ImageFont.truetype(regular, int(h_px * ratios[4])),
        }
    except OSError:
        default = ImageFont.load_default()
        return {k: default for k in ("header", "model", "sub", "mono", "scan")}


from dataclasses import dataclass


@dataclass
class CardCanvas:
    """Bundle the PIL drawing context + card dimensions so helpers don't need 8 positional args."""
    draw: object
    card: object
    qr_img: object
    fonts: dict
    w_px: int
    h_px: int
    margin: int


def _draw_landscape_card(canvas: CardCanvas, equipment: dict) -> None:
    """Render the landscape (wide) QR card variant: QR left, text right."""
    draw, fonts, w_px, h_px, margin = canvas.draw, canvas.fonts, canvas.w_px, canvas.h_px, canvas.margin
    qr_size = h_px - 2 * margin
    qr_img = canvas.qr_img.resize((qr_size, qr_size))
    canvas.card.paste(qr_img, (margin, margin))

    text_x = margin + qr_size + margin
    text_width = w_px - text_x - margin

    draw.text((text_x, margin), "GymAxis", fill=_BRAND_BLUE, font=fonts["header"])
    y = draw.textbbox((text_x, margin), "GymAxis", font=fonts["header"])[3] + int(margin * 0.3)
    draw.line([(text_x, y), (w_px - margin, y)], fill=_BRAND_BLUE, width=3)
    y += int(margin * 0.5)

    manufacturer = equipment.get("manufacturer") or equipment.get("brand") or ""
    model = equipment.get("model", "")
    serial = equipment.get("serial_number", "")

    if manufacturer:
        for line in _wrap_text_to_width(draw, manufacturer, fonts["model"], text_width):
            draw.text((text_x, y), line, fill=_INK, font=fonts["model"])
            y += draw.textbbox((0, 0), line, font=fonts["model"])[3] + 2
    if model:
        for line in _wrap_text_to_width(draw, model, fonts["sub"], text_width):
            draw.text((text_x, y), line, fill=_INK, font=fonts["sub"])
            y += draw.textbbox((0, 0), line, font=fonts["sub"])[3] + 2
    if serial:
        draw.text((text_x, y), serial, fill=_SERIAL_COLOUR, font=fonts["mono"])

    scan_text = "Scan to report fault"
    scan_bbox = draw.textbbox((0, 0), scan_text, font=fonts["scan"])
    draw.text((text_x, h_px - margin - (scan_bbox[3] - scan_bbox[1])), scan_text, fill=_MUTED, font=fonts["scan"])


def _draw_portrait_card(canvas: CardCanvas, equipment: dict) -> None:
    """Render the portrait (tall) QR card variant: header → QR → footer text."""
    draw, fonts, w_px, h_px, margin = canvas.draw, canvas.fonts, canvas.w_px, canvas.h_px, canvas.margin
    draw.text((margin, margin), "GymAxis", fill=_BRAND_BLUE, font=fonts["header"])
    y = draw.textbbox((margin, margin), "GymAxis", font=fonts["header"])[3] + int(margin * 0.2)
    draw.line([(margin, y), (w_px - margin, y)], fill=_BRAND_BLUE, width=3)
    y += int(margin * 0.3)

    manufacturer = equipment.get("manufacturer") or equipment.get("brand") or ""
    model = equipment.get("model", "")
    if manufacturer:
        draw.text((margin, y), manufacturer[:30], fill=_INK, font=fonts["model"])
        y += draw.textbbox((0, 0), "Ag", font=fonts["model"])[3] + 2
    if model:
        draw.text((margin, y), model[:30], fill=_INK, font=fonts["sub"])
        y += draw.textbbox((0, 0), "Ag", font=fonts["sub"])[3] + int(margin * 0.4)

    available = h_px - y - margin - int(margin * 2)
    qr_size = min(w_px - 2 * margin, available)
    qr_img = canvas.qr_img.resize((qr_size, qr_size))
    canvas.card.paste(qr_img, ((w_px - qr_size) // 2, y))
    y += qr_size + int(margin * 0.4)

    serial = equipment.get("serial_number", "")
    if serial:
        serial_bbox = draw.textbbox((0, 0), serial, font=fonts["mono"])
        draw.text(((w_px - (serial_bbox[2] - serial_bbox[0])) // 2, y), serial, fill=_SERIAL_COLOUR, font=fonts["mono"])

    scan_text = "Scan to report fault"
    scan_bbox = draw.textbbox((0, 0), scan_text, font=fonts["scan"])
    scan_w = scan_bbox[2] - scan_bbox[0]
    draw.text(((w_px - scan_w) // 2, h_px - margin - (scan_bbox[3] - scan_bbox[1])),
              scan_text, fill=_MUTED, font=fonts["scan"])


@router.get("/equipment/{equipment_id}/qr-card")
async def generate_qr_card(
    equipment_id: str,
    request: Request,
    size: str = "62x35",
    user: dict = Depends(get_current_user),
):
    """Generate a branded QR card PNG (GymAxis header + make/model + QR).
    Size presets: 62x35 (default), 62x62, 50x50, card (90x50), a4.
    """
    from PIL import Image, ImageDraw

    # Iter 216h123 — MOD HQ rebind. See utils.mod_scope.
    from utils.mod_scope import resolve_mod_query_filter
    org_filter = await resolve_mod_query_filter(user, None)
    equipment = await db.equipment.find_one({"id": equipment_id, **org_filter}, {"_id": 0})
    if not equipment:
        raise HTTPException(status_code=404, detail="Equipment not found")
    if size not in QR_CARD_PRESETS:
        raise HTTPException(status_code=400,
                            detail=f"Unknown size preset. Options: {list(QR_CARD_PRESETS)}")

    width_mm, height_mm, dpi = QR_CARD_PRESETS[size]
    w_px, h_px = _mm_to_px(width_mm, dpi), _mm_to_px(height_mm, dpi)
    margin = _mm_to_px(2, dpi)
    landscape = width_mm >= height_mm

    base_url = resolve_frontend_url(request)
    qr_img = _build_qr_image(equipment_id, base_url)
    fonts = _load_qr_fonts(h_px, landscape)
    card = Image.new("RGB", (w_px, h_px), "white")
    draw = ImageDraw.Draw(card)

    if landscape:
        canvas = CardCanvas(draw=draw, card=card, qr_img=qr_img, fonts=fonts, w_px=w_px, h_px=h_px, margin=margin)
        _draw_landscape_card(canvas, equipment)
    else:
        canvas = CardCanvas(draw=draw, card=card, qr_img=qr_img, fonts=fonts, w_px=w_px, h_px=h_px, margin=margin)
        _draw_portrait_card(canvas, equipment)

    buf = io.BytesIO()
    card.save(buf, format="PNG", dpi=(dpi, dpi))
    buf.seek(0)

    filename_serial = (equipment.get("serial_number") or equipment_id).replace("/", "-")
    return Response(
        content=buf.getvalue(),
        media_type="image/png",
        headers={"Content-Disposition": f'inline; filename="qr-card-{filename_serial}-{size}.png"'}
    )



