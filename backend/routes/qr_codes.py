async def _upload_fault_photo(photo: UploadFile, org_id: str) -> tuple[str | None, str | None]:
    """Upload a fault photo and return (url, base64)."""
    if not photo or not photo.filename:
        return None, None
    try:
        data = await photo.read()
        ext = photo.filename.rsplit(".", 1)[-1] if "." in photo.filename else "jpg"
        path = f"{APP_NAME}/fault-photos/{org_id}/{uuid.uuid4()}.{ext}"
        result = put_object(path, data, photo.content_type or "image/jpeg")
        return result.get("url", result["path"]), base64.b64encode(data).decode("utf-8")
    except Exception as e:
        logger.error(f"Photo upload failed: {e}")
        return None, None


async def _run_qr_triage(equipment: dict, description: str, severity: str, photo_base64: str | None, issue_id: str) -> dict | None:
    """Run AI triage on a QR-reported fault."""
    try:
        chat = LlmChat(
            api_key=EMERGENT_LLM_KEY,
            session_id=f"qr_triage_{issue_id}_{datetime.now().timestamp()}",
            system_message=_QR_TRIAGE_SYSTEM_MSG,
        ).with_model("openai", "gpt-4o")

        prompt = (
            f"Fault report for: {equipment.get('equipment_type', 'Unknown')} - {equipment.get('name', '')}\n"
            f"Serial: {equipment.get('serial_number', 'N/A')}\nManufacturer: {equipment.get('manufacturer', 'N/A')}\n"
            f"Fault description: {description}\nReported severity: {severity}\n"
            f"{'Photo attached for analysis.' if photo_base64 else 'No photo provided.'}\n\nPerform triage."
        )
        msg = UserMessage(text=prompt, file_contents=[ImageContent(image_base64=photo_base64)]) if photo_base64 else UserMessage(text=prompt)
        raw = await chat.send_message(msg)

        cleaned = raw.strip()
        if cleaned.startswith("```"):
            cleaned = cleaned.split("\n", 1)[1].rsplit("```", 1)[0].strip()
        if cleaned.startswith("json"):
            cleaned = cleaned[4:].strip()
        parsed = json_module.loads(cleaned)

        await db.issues.update_one({"id": issue_id}, {"$set": {"ai_triage": raw, "ai_triage_parsed": parsed, "triage_at": datetime.now(timezone.utc).isoformat()}})
        return parsed
    except Exception as e:
        logger.error(f"AI triage failed for QR fault {issue_id}: {e}")
        return None


