@router.get("/public/equipment/{equipment_id}/check-items")
async def public_check_items(equipment_id: str):
    """Public endpoint – returns the maintenance check items for the equipment's type."""
    equipment = await db.equipment.find_one({"id": equipment_id}, {"_id": 0})
    if not equipment:
        raise HTTPException(status_code=404, detail="Equipment not found")

    eq_type = equipment.get("equipment_type", "")
    tasks = _get_tasks_for_type(eq_type)

    # Also check for any custom templates for this org
    org_id = equipment.get("organization_id")
    custom_templates = []
    if org_id:
        customs = await db.custom_check_templates.find(
            {"organization_id": org_id}, {"_id": 0}
        ).to_list(20)
        custom_templates = [{"id": c["id"], "name": c["name"], "items": c.get("items", [])} for c in customs]

    return {
        "equipment_id": equipment_id,
        "equipment_name": equipment.get("name", ""),
        "equipment_type": eq_type,
        "serial_number": equipment.get("serial_number", ""),
        "check_items": tasks,
        "custom_templates": custom_templates,
    }


@router.post("/public/equipment/{equipment_id}/complete-check")
async def public_complete_check(equipment_id: str, data: dict):
    """Public endpoint – complete a maintenance check sheet via QR scan. No auth required."""
    equipment = await db.equipment.find_one({"id": equipment_id}, {"_id": 0})
    if not equipment:
        raise HTTPException(status_code=404, detail="Equipment not found")

    items = data.get("items", [])
    if not items:
        raise HTTPException(status_code=400, detail="No check items provided")

    eq_type = equipment.get("equipment_type", "")
    serial = equipment.get("serial_number") or equipment.get("name", "")
    completed_by = data.get("completed_by", "QR Scan User")
    notes = data.get("notes", "")
    today = datetime.now(timezone.utc).strftime("%Y-%m-%d")

    # Use same template_name format as desktop so it syncs: "{type} - {serial}"
    template_name = f"{eq_type} - {serial}" if eq_type and serial else equipment.get("name", "Unknown")

    sheet_doc = {
        "id": str(uuid.uuid4()),
        "user_id": "qr-scan",
        "organization_id": equipment.get("organization_id"),
        "completed_by": completed_by,
        "equipment_category": eq_type,
        "template_name": template_name,
        "template_id": equipment_id,
        "serial_number": serial,
        "equipment_id": equipment_id,
        "checks": {item["name"]: item.get("checked", False) for item in items},
        "items": items,
        "notes": notes,
        "date": today,
        "completed_date": today,
        "source": "qr_scan",
        "created_at": datetime.now(timezone.utc).isoformat(),
    }
    await db.check_sheets.insert_one(sheet_doc)
    sheet_doc.pop("_id", None)

    return {
        "success": True,
        "sheet_id": sheet_doc["id"],
        "template_name": template_name,
        "message": f"Maintenance check completed for {equipment.get('name', 'equipment')}. This is now visible on the dashboard.",
    }
