# Iter 216b — QR scan-URL resolution.
# Production deployments need a guaranteed way to force the QR URL even if
# the ingress headers are funky. So the resolution order is:
#   1. FRONTEND_URL env var — IF it points at a real production host (i.e.
#      not an Emergent preview / internal cluster URL). This is the "Custom
#      Keys" knob a master admin should set in the deployment secrets.
#      Setting `FRONTEND_URL=https://gymaxisai.com` makes every QR ever
#      generated by that backend point to gymaxisai.com, full stop.
#   2. PRODUCTION_FRONTEND_URL env var — alias of #1 for explicit naming.
#   3. X-Forwarded-Host header (ingress-set; reliable in preview).
#   4. Origin header (browser-set; CF preview workers may rewrite).
#   5. Referer.
#   6. Host header.
#   7. REACT_APP_BACKEND_URL env var (final fallback).
# Hosts that look like Emergent's *internal* cluster (cluster-XX.preview.
# emergentcf.cloud) are always rejected — they're not user-reachable.
_PRODUCTION_FRONTEND_URL = (os.environ.get("PRODUCTION_FRONTEND_URL") or "").rstrip("/")
_CONFIGURED_FRONTEND_URL = (os.environ.get("FRONTEND_URL") or "").rstrip("/")
_FALLBACK_FRONTEND_URL = (
    os.environ.get("REACT_APP_BACKEND_URL") or ""
).replace("/api", "").rstrip("/")


def _is_internal_cluster_host(url: str) -> bool:
    """Return True if URL points to Emergent's internal cluster hostname."""
    return "emergentcf.cloud" in url or "cluster-" in url


def _is_emergent_preview_host(url: str) -> bool:
    """Return True if URL points to an Emergent preview domain (not a real prod host)."""
    return "emergentagent.com" in url


def _hard_override_url() -> str | None:
    """Return the explicitly-configured production URL if it's a 'real'
    customer-facing host. Preview/cluster URLs are rejected so we don't
    accidentally hard-override to the dev environment in production."""
    for candidate in (_PRODUCTION_FRONTEND_URL, _CONFIGURED_FRONTEND_URL):
        if not candidate:
            continue
        if _is_internal_cluster_host(candidate) or _is_emergent_preview_host(candidate):
            continue
        return candidate
    return None


def resolve_frontend_url(request: Request | None) -> str:
    """Derive the public-facing base URL for QR scan links.

    A hard-coded `FRONTEND_URL` / `PRODUCTION_FRONTEND_URL` env var ALWAYS
    wins (provided it's a real production host, not a preview / cluster
    URL). Otherwise we use the actual host of the incoming request so QRs
    downloaded from gymaxisai.com say gymaxisai.com and QRs downloaded
    from preview say preview."""
    # 1. Hard override from deployment secrets — always wins for prod.
    override = _hard_override_url()
    if override:
        return override

    candidates: list[str] = []
    if request is not None:
        # 2. X-Forwarded-Host (ingress-set, most reliable header).
        xfh = (request.headers.get("x-forwarded-host") or "").strip()
        if xfh:
            xfproto = (request.headers.get("x-forwarded-proto") or "https").split(",")[0].strip()
            candidates.append(f"{xfproto}://{xfh.split(',')[0].strip()}")

        # 3. Origin header (browser-set; CF preview workers may rewrite).
        origin = (request.headers.get("origin") or "").strip()
        if origin:
            candidates.append(origin)

        # 4. Referer.
        referer = (request.headers.get("referer") or "").strip()
        if referer:
            from urllib.parse import urlparse as _urlparse
            p = _urlparse(referer)
            if p.scheme and p.netloc:
                candidates.append(f"{p.scheme}://{p.netloc}")

        # 5. Host header.
        host_hdr = (request.headers.get("host") or "").strip()
        if host_hdr:
            xfproto = (request.headers.get("x-forwarded-proto") or "https").split(",")[0].strip()
            candidates.append(f"{xfproto}://{host_hdr}")

    for c in candidates:
        c = c.rstrip("/")
        if not c or _is_internal_cluster_host(c):
            continue
        return c

    # Last-ditch fallback (cron / batch jobs, no request, no override).
    return _CONFIGURED_FRONTEND_URL or _PRODUCTION_FRONTEND_URL or _FALLBACK_FRONTEND_URL


# Backwards-compat constant for any caller still importing it directly.
# Note: prefer `resolve_frontend_url(request)` everywhere new.
FRONTEND_URL = _hard_override_url() or _CONFIGURED_FRONTEND_URL or _PRODUCTION_FRONTEND_URL or _FALLBACK_FRONTEND_URL


@router.get("/equipment/{equipment_id}/qr-code")
async def generate_qr_code(equipment_id: str, request: Request, size: int = 300, user: dict = Depends(get_current_user)):
    """Generate a QR code PNG for a piece of equipment. Scan opens the public report page."""
    # Iter 216h123 — MOD HQ users can fetch a QR for any equipment
    # under any of their child gyms. See utils.mod_scope.
    from utils.mod_scope import resolve_mod_query_filter
    org_filter = await resolve_mod_query_filter(user, None)
    equipment = await db.equipment.find_one({"id": equipment_id, **org_filter}, {"_id": 0})
    if not equipment:
        raise HTTPException(status_code=404, detail="Equipment not found")

    base_url = resolve_frontend_url(request)
    scan_url = f"{base_url}/scan/{equipment_id}"

    qr = qrcode.QRCode(version=1, error_correction=qrcode.constants.ERROR_CORRECT_H, box_size=10, border=2)
    qr.add_data(scan_url)
    qr.make(fit=True)
    img = qr.make_image(fill_color="black", back_color="white").resize((size, size))

    buf = io.BytesIO()
    img.save(buf, format="PNG")
    buf.seek(0)

    return Response(
        content=buf.getvalue(),
        media_type="image/png",
        headers={"Content-Disposition": f'inline; filename="qr-{equipment.get("serial_number", equipment_id)}.png"'}
    )


