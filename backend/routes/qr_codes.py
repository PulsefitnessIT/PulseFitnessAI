def _get_tasks_for_type(equipment_type: str) -> list:
    if not equipment_type:
        return DEFAULT_TASKS
    lower = equipment_type.lower()
    for key, tasks in EQUIPMENT_TYPE_TASKS.items():
        if key in lower or lower in key:
            return tasks
