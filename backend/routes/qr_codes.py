def _parse_coverage_date(date_str: str | None) -> tuple[bool, int | None]:
    """Parse a date string and return (is_active, days_remaining)."""
    if not date_str:
        return False, None
    try:
        expiry = datetime.fromisoformat(date_str)
        if expiry.tzinfo is None:
            expiry = expiry.replace(tzinfo=timezone.utc)
        days = (expiry - datetime.now(timezone.utc)).days
        return days > 0, days
    except Exception:
        return False, None


def _build_coverage_status(equipment: dict) -> dict:
    """Build coverage info from equipment warranty/contract fields."""
    w_active, w_days = _parse_coverage_date(equipment.get("warranty_expiry"))
    c_active, c_days = _parse_coverage_date(equipment.get("sla_expiry"))
    covered = w_active or c_active
    if w_active:
        ctype, label = "warranty", "Under Warranty"
    elif c_active:
        ctype, label = "contract", "Under Contract"
    else:
        ctype, label = "none", "No Warranty / Contract"
    return {
        "covered": covered, "type": ctype, "label": label,
        "warranty_active": w_active, "warranty_days_remaining": w_days,
        "warranty_expiry": equipment.get("warranty_expiry"),
        "contract_active": c_active, "contract_days_remaining": c_days,
        "sla_contract_ref": equipment.get("sla_contract_ref"), "sla_expiry": equipment.get("sla_expiry"),
    }


